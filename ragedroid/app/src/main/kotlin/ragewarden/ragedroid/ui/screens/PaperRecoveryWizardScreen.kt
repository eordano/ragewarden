private enum class PaperRecoveryStep { Generate, Verify, Done }

private val LOADING_PHRASE: ImmutableList<String> = persistentListOf(
    "...", "...", "...", "...", "...", "...",
    "...", "...", "...", "...", "...", "...",
    "...", "...", "...", "...", "...", "...",
    "...", "...", "...", "...", "...", "...",
)

@Composable
fun PaperRecoveryWizardScreen(
    onBack: () -> Unit,
    onComplete: () -> Unit,
    onToast: (String) -> Unit = {},
    recipientStore: RecipientStore? = null,
    accountId: String? = null,
) {
    val c = rageColors
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var step by remember { mutableStateOf(PaperRecoveryStep.Generate) }
    var generated by remember { mutableStateOf<GeneratedRecovery?>(null) }
    var saving by remember { mutableStateOf(false) }
    var saveError by remember { mutableStateOf<String?>(null) }
    LaunchedEffect(Unit) {
        if (generated == null) {
            generated = withContext(Dispatchers.IO) { Recovery.generate() }
        }
    }

    val attemptPersist: () -> Unit = persist@{
        if (saving) return@persist
        val ready = generated
        if (ready == null) {
            saveError = "Recovery phrase is still being generated. Try again in a moment."
            return@persist
        }
        if (recipientStore == null || accountId.isNullOrBlank()) {
            saveError = "Configuration error: no active account. Sign in and try again."
            return@persist
        }
        saving = true
        scope.launch {
            val result = runCatching { recipientStore.add(accountId, enrollRecovery(ready)) }
            saving = false
            result.onSuccess {
                saveError = null
                onComplete()
            }.onFailure { e ->
                saveError = "We couldn't save your recovery identity. Copy these 24 words now and tap Retry, or Cancel to abort enrolment."
                onToast("Save failed: ${e.message ?: e::class.simpleName}")
            }
        }
    }
    val mnemonic = generated?.mnemonic
    val phrase: ImmutableList<String> = remember(mnemonic) {
        mnemonic?.split(' ', '\t', '\n')
            ?.filter { it.isNotBlank() }
            ?.toImmutableList()
            ?: LOADING_PHRASE
    }
    val challenge = remember {
        val rng = Random.Default
        val set = mutableSetOf<Int>()
        while (set.size < 3) {
            set.add(rng.nextInt(phrase.size))
        }
        set.sorted()
    }
    val answers = remember { mutableStateOf(emptyMap<Int, String>()) }

    val allCorrect = challenge.all { i ->
        (answers.value[i] ?: "").trim().lowercase() == phrase[i]
    }

    Column(modifier = Modifier.fillMaxSize().background(c.background)) {
        when (step) {
            PaperRecoveryStep.Generate -> {
                AppBar(
                    title = "Paper recovery",
                    subtitle = "Step 1 of 2",
                    leading = {
                        IconBtn(
                            icon = Icons.AutoMirrored.Outlined.ArrowBack,
                            contentDescription = "Back",
                            onClick = onBack,
                        )
                    },
                )
                Column(
                    modifier = Modifier
                        .fillMaxSize()
                        .verticalScroll(rememberScrollState())
                        .padding(start = 18.dp, end = 18.dp, bottom = 18.dp),
                ) {
                    Text(
                        text = "Write these 24 words down.",
                        style = RageType.h1.copy(
                            fontSize = 22.sp,
                            lineHeight = 26.sp,
                            letterSpacing = (-0.015).em,
                        ),
                        color = c.fgEmphasis,
                    )
                    Spacer(modifier = Modifier.height(10.dp))
                    Text(
                        text = "This phrase is your last-resort recovery identity. Anyone with all 24 words can decrypt every protected item. Never type it into a screen.",
                        style = RageType.body.copy(
                            fontSize = 14.5.sp,
                            lineHeight = 22.sp,
                        ),
                        color = c.fgPrimary,
                    )
                    Spacer(modifier = Modifier.height(16.dp))
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .background(c.surfaceElevated, RoundedCornerShape(12.dp))
                            .border(1.dp, c.border, RoundedCornerShape(12.dp))
                            .padding(horizontal = 14.dp, vertical = 16.dp),
                    ) {
                        val rows = phrase.size / 2
                        for (rowIndex in 0 until rows) {
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.spacedBy(14.dp),
                            ) {
                                PhraseWord(
                                    index = rowIndex,
                                    word = phrase[rowIndex],
                                    modifier = Modifier.weight(1f),
                                )
                                PhraseWord(
                                    index = rowIndex + rows,
                                    word = phrase[rowIndex + rows],
                                    modifier = Modifier.weight(1f),
                                )
                            }
                            if (rowIndex < rows - 1) {
                                Spacer(modifier = Modifier.height(8.dp))
                            }
                        }
                    }
                    Spacer(modifier = Modifier.height(14.dp))
                    WarningCalloutPaper(
                        text = "Don't screenshot. Don't type into a password manager. Print, write by hand, or split across two safes.",
                    )
                    Spacer(modifier = Modifier.height(14.dp))
                    RageButton(
                        label = "Print recovery sheet",
                        onClick = {
                            val ready = generated
                            if (ready == null) {
                                onToast("Recovery phrase is still being generated. Try again in a moment.")
                            } else {
                                printRecoverySheet(context, ready)
                            }
                        },
                        icon = Icons.Outlined.Description,
                        variant = ButtonVariant.Secondary,
                        fullWidth = true,
                    )
                    Spacer(modifier = Modifier.height(8.dp))
                    RageButton(
                        label = "I've written them down",
                        onClick = { step = PaperRecoveryStep.Verify },
                        icon = Icons.AutoMirrored.Outlined.ArrowForward,
                        fullWidth = true,
                    )
                }
            }
            PaperRecoveryStep.Verify -> {
                AppBar(
                    title = "Confirm",
                    subtitle = "Step 2 of 2",
                    leading = {
                        IconBtn(
                            icon = Icons.AutoMirrored.Outlined.ArrowBack,
                            contentDescription = "Back",
                            onClick = { step = PaperRecoveryStep.Generate },
                        )
                    },
                )
                Column(
                    modifier = Modifier
                        .fillMaxSize()
                        .verticalScroll(rememberScrollState())
                        .padding(start = 18.dp, end = 18.dp, bottom = 18.dp),
                ) {
                    Text(
                        text = "Type 3 words to confirm.",
                        style = RageType.h1.copy(
                            fontSize = 22.sp,
                            lineHeight = 26.sp,
                            letterSpacing = (-0.015).em,
                        ),
                        color = c.fgEmphasis,
                    )
                    Spacer(modifier = Modifier.height(10.dp))
                    Text(
                        text = "We'll only verify these three positions. We never see or store the rest.",
                        style = RageType.body.copy(fontSize = 14.5.sp, lineHeight = 22.sp),
                        color = c.fgSecondary,
                    )
                    Spacer(modifier = Modifier.height(16.dp))
                    Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                        challenge.forEach { i ->
                            val ans = answers.value[i] ?: ""
                            val correct = ans.isNotEmpty() && ans.trim().lowercase() == phrase[i]
                            val wrong = ans.isNotEmpty() && !correct
                            Field(label = "Word #${i + 1}") {
                                Box {
                                    Box(
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .border(
                                                1.dp,
                                                when {
                                                    correct -> c.success
                                                    wrong -> c.danger
                                                    else -> c.border
                                                },
                                                RoundedCornerShape(8.dp),
                                            ),
                                    ) {
                                        TextInput(
                                            value = ans,
                                            onValueChange = { v ->
                                                answers.value = answers.value + (i to v)
                                            },
                                            placeholder = "Word ${i + 1}",
                                            mono = true,
                                        )
                                    }
                                    if (correct) {
                                        Icon(
                                            imageVector = Icons.Outlined.Check,
                                            contentDescription = null,
                                            tint = c.success,
                                            modifier = Modifier
                                                .align(Alignment.CenterEnd)
                                                .padding(end = 12.dp)
                                                .size(16.dp),
                                        )
                                    }
                                }
                            }
                        }
                    }
                    Spacer(modifier = Modifier.height(8.dp))
                    RageButton(
                        label = if (allCorrect) "Confirm recipient" else "All three must match",
                        onClick = { step = PaperRecoveryStep.Done },
                        icon = Icons.Outlined.Check,
                        fullWidth = true,
                        enabled = allCorrect,
                    )
                }
            }
            PaperRecoveryStep.Done -> {
                AppBar(title = "Recipient enrolled")
                Column(
                    modifier = Modifier
                        .fillMaxSize()
                        .padding(start = 24.dp, end = 24.dp, top = 24.dp, bottom = 18.dp),
                ) {
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .weight(1f),
                        verticalArrangement = Arrangement.Center,
                        horizontalAlignment = Alignment.CenterHorizontally,
                    ) {
                        Box(
                            modifier = Modifier
                                .size(64.dp)
                                .background(c.success, RoundedCornerShape(32.dp)),
                            contentAlignment = Alignment.Center,
                        ) {
                            Icon(
                                imageVector = Icons.Outlined.Check,
                                contentDescription = null,
                                tint = c.background,
                                modifier = Modifier.size(32.dp),
                            )
                        }
                        Spacer(modifier = Modifier.height(18.dp))
                        Text(
                            text = "Recovery identity ready.",
                            style = RageType.h1.copy(
                                fontSize = 26.sp,
                                lineHeight = 30.sp,
                                letterSpacing = (-0.015).em,
                            ),
                            color = c.fgEmphasis,
                            textAlign = TextAlign.Center,
                        )
                        Spacer(modifier = Modifier.height(12.dp))
                        Text(
                            text = "Stored offline as a paper backup. We'll add it as a stanza next time you re-encrypt -- no tap required, since the public key alone is enough to encrypt.",
                            style = RageType.body.copy(fontSize = 15.sp, lineHeight = 22.sp),
                            color = c.fgSecondary,
                            textAlign = TextAlign.Center,
                            modifier = Modifier.widthIn(max = 320.dp),
                        )
                    }
                    RageButton(
                        label = if (saving) "Saving..." else "Done",
                        onClick = attemptPersist,
                        icon = Icons.AutoMirrored.Outlined.ArrowForward,
                        fullWidth = true,
                        enabled = !saving,
                    )
                }
            }
        }
    }

    val errorMessage = saveError
    if (errorMessage != null) {
        val isMisconfig = recipientStore == null || accountId.isNullOrBlank()
        AlertDialog(
            onDismissRequest = {},
            title = { Text("Save failed") },
            text = {
                Column {
                    Text(
                        text = errorMessage,
                        style = RageType.body.copy(fontSize = 14.sp, lineHeight = 20.sp),
                        color = c.fgPrimary,
                    )
                    if (!isMisconfig) {
                        Spacer(modifier = Modifier.height(12.dp))
                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .background(c.surfaceSunken, RoundedCornerShape(8.dp))
                                .border(1.dp, c.border, RoundedCornerShape(8.dp))
                                .padding(horizontal = 12.dp, vertical = 10.dp),
                        ) {
                            Text(
                                text = phrase.joinToString(" "),
                                style = RageType.mono.copy(
                                    fontFamily = FontFamily.Monospace,
                                    fontSize = 13.sp,
                                    lineHeight = 19.sp,
                                ),
                                color = c.fgEmphasis,
                            )
                        }
                    }
                }
            },
            confirmButton = {
                if (isMisconfig) {
                    TextButton(onClick = {
                        saveError = null
                        onBack()
                    }) { Text("Back") }
                } else {
                    TextButton(
                        enabled = !saving,
                        onClick = {
                            saveError = null
                            attemptPersist()
                        },
                    ) { Text("Retry") }
                }
            },
            dismissButton = {
                if (!isMisconfig) {
                    TextButton(onClick = {
                        saveError = null
                        onBack()
                    }) { Text("Cancel") }
                }
            },
        )
    }
}

@Composable
private fun PhraseWord(
    index: Int,
    word: String,
    modifier: Modifier = Modifier,
) {
    val c = rageColors
    Row(
        modifier = modifier,
        verticalAlignment = Alignment.Bottom,
        horizontalArrangement = Arrangement.spacedBy(8.dp),
    ) {
        Text(
            text = (index + 1).toString().padStart(2, '0'),
            style = RageType.mono.copy(fontSize = 11.sp),
            color = c.fgSecondary,
            modifier = Modifier.widthIn(min = 22.dp),
            textAlign = TextAlign.End,
        )
        Text(
            text = word,
            style = RageType.mono.copy(
                fontSize = 14.sp,
                fontWeight = FontWeight.Medium,
            ),
            color = c.fgEmphasis,
        )
    }
}

private fun printRecoverySheet(context: Context, recovery: GeneratedRecovery) {
    val printManager = context.getSystemService(Context.PRINT_SERVICE) as? PrintManager ?: return
    val jobName = context.getString(R.string.ragedroid_paper_recovery_sheet)
    val adapter = RecoverySheetPrintAdapter(jobName, recovery)
    printManager.print(jobName, adapter, PrintAttributes.Builder().build())
}

private fun fingerprintFor(armoredPubkey: String): String {
    val digest = MessageDigest.getInstance("SHA-256").digest(armoredPubkey.toByteArray(Charsets.UTF_8))
    return digest.take(8).joinToString(":") { "%02x".format(it) }
}

private class RecoverySheetPrintAdapter(
    private val jobName: String,
    private val recovery: GeneratedRecovery,
) : PrintDocumentAdapter() {

    private var pageWidth: Int = 0
    private var pageHeight: Int = 0

    override fun onLayout(
        oldAttributes: PrintAttributes?,
        newAttributes: PrintAttributes,
        cancellationSignal: CancellationSignal?,
        callback: LayoutResultCallback,
        extras: Bundle?,
    ) {
        if (cancellationSignal?.isCanceled == true) {
            callback.onLayoutCancelled()
            return
        }
        val mediaSize = newAttributes.mediaSize ?: PrintAttributes.MediaSize.ISO_A4
        val resolution = newAttributes.resolution ?: PrintAttributes.Resolution("default", "default", 72, 72)
        pageWidth = (mediaSize.widthMils / 1000.0 * resolution.horizontalDpi).toInt()
        pageHeight = (mediaSize.heightMils / 1000.0 * resolution.verticalDpi).toInt()

        val info = PrintDocumentInfo.Builder(jobName)
            .setContentType(PrintDocumentInfo.CONTENT_TYPE_DOCUMENT)
            .setPageCount(1)
            .build()
        callback.onLayoutFinished(info, true)
    }

    override fun onWrite(
        pages: Array<out PageRange>?,
        destination: ParcelFileDescriptor,
        cancellationSignal: CancellationSignal?,
        callback: WriteResultCallback,
    ) {
        if (cancellationSignal?.isCanceled == true) {
            callback.onWriteCancelled()
            return
        }
        val document = PdfDocument()
        try {
            val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, 0).create()
            val page = document.startPage(pageInfo)
            drawSheet(page.canvas, pageWidth, pageHeight)
            document.finishPage(page)
            FileOutputStream(destination.fileDescriptor).use { out ->
                document.writeTo(out)
            }
            callback.onWriteFinished(arrayOf(PageRange.ALL_PAGES))
        } catch (e: IOException) {
            callback.onWriteFailed(e.localizedMessage)
        } finally {
            document.close()
        }
    }

    private fun drawSheet(canvas: android.graphics.Canvas, w: Int, h: Int) {
        val dpi = 72f
        val margin = dpi * 0.75f
        val contentLeft = margin
        val contentRight = w - margin
        var y = margin + dpi * 0.4f

        val titlePaint = Paint().apply {
            isAntiAlias = true
            color = 0xFF111111.toInt()
            textSize = 22f
            typeface = Typeface.create(Typeface.SANS_SERIF, Typeface.BOLD)
        }
        val subtitlePaint = Paint().apply {
            isAntiAlias = true
            color = 0xFF444444.toInt()
            textSize = 11f
            typeface = Typeface.SANS_SERIF
        }
        val bodyPaint = Paint().apply {
            isAntiAlias = true
            color = 0xFF222222.toInt()
            textSize = 10f
            typeface = Typeface.SANS_SERIF
        }
        val monoPaint = Paint().apply {
            isAntiAlias = true
            color = 0xFF000000.toInt()
            textSize = 13f
            typeface = Typeface.MONOSPACE
        }
        val labelPaint = Paint().apply {
            isAntiAlias = true
            color = 0xFF777777.toInt()
            textSize = 8f
            typeface = Typeface.create(Typeface.SANS_SERIF, Typeface.BOLD)
        }
        val rulePaint = Paint().apply {
            color = 0xFF888888.toInt()
            strokeWidth = 0.6f
        }

        canvas.drawText("RageDroid paper recovery sheet", contentLeft, y, titlePaint)
        y += 18f
        val date = SimpleDateFormat("yyyy-MM-dd HH:mm z", Locale.US).format(Date())
        val fp = fingerprintFor(recovery.armoredPubkey)
        canvas.drawText("Generated $date    Fingerprint $fp", contentLeft, y, subtitlePaint)
        y += 18f
        canvas.drawLine(contentLeft, y, contentRight, y, rulePaint)
        y += 22f

        val warning = "Anyone with all 24 words can decrypt every protected item. Store this sheet offline. " +
            "Do not photograph it. Do not type it into a password manager."
        y = drawWrapped(canvas, warning, bodyPaint, contentLeft, y, contentRight - contentLeft, 13f)
        y += 14f

        canvas.drawText("RECOVERY WORDS", contentLeft, y, labelPaint)
        y += 14f

        val words = recovery.mnemonic.split(' ', '\t', '\n').filter { it.isNotBlank() }
        val cols = 4
        val rows = (words.size + cols - 1) / cols
        val colWidth = (contentRight - contentLeft) / cols
        val rowHeight = 22f
        for (r in 0 until rows) {
            for (col in 0 until cols) {
                val idx = r * cols + col
                if (idx >= words.size) continue
                val x = contentLeft + col * colWidth
                val numLabel = (idx + 1).toString().padStart(2, '0') + "."
                canvas.drawText(numLabel, x, y + r * rowHeight, labelPaint)
                canvas.drawText(words[idx], x + 22f, y + r * rowHeight, monoPaint)
            }
        }
        y += rows * rowHeight + 14f

        canvas.drawLine(contentLeft, y, contentRight, y, rulePaint)
        y += 18f
        canvas.drawText("PUBLIC KEY (armored)", contentLeft, y, labelPaint)
        y += 12f
        val pubMono = Paint(monoPaint).apply { textSize = 8.5f }
        for (line in recovery.armoredPubkey.split('\n')) {
            if (y > h - margin) break
            canvas.drawText(line, contentLeft, y, pubMono)
            y += 11f
        }
    }

    private fun drawWrapped(
        canvas: android.graphics.Canvas,
        text: String,
        paint: Paint,
        x: Float,
        startY: Float,
        maxWidth: Float,
        lineHeight: Float,
    ): Float {
        var y = startY
        val words = text.split(' ')
        val line = StringBuilder()
        for (word in words) {
            val candidate = if (line.isEmpty()) word else "$line $word"
            if (paint.measureText(candidate) <= maxWidth) {
                line.clear()
                line.append(candidate)
            } else {
                canvas.drawText(line.toString(), x, y, paint)
                y += lineHeight
                line.clear()
                line.append(word)
            }
        }
        if (line.isNotEmpty()) {
            canvas.drawText(line.toString(), x, y, paint)
            y += lineHeight
        }
        return y
    }
}

@Composable
private fun WarningCalloutPaper(text: String) {
    val c = rageColors
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .background(c.surfaceSunken, RoundedCornerShape(8.dp))
            .border(1.dp, c.border, RoundedCornerShape(8.dp)),
        verticalAlignment = Alignment.Top,
    ) {
        Box(
            modifier = Modifier
                .width(3.dp)
                .fillMaxHeight()
                .background(c.warning),
        )
        Text(
            text = text,
            style = RageType.body.copy(
                fontSize = 13.sp,
                lineHeight = 19.sp,
                fontStyle = FontStyle.Italic,
            ),
            color = c.fgSecondary,
            modifier = Modifier.padding(start = 10.dp, top = 10.dp, end = 12.dp, bottom = 10.dp),
        )
    }
}
