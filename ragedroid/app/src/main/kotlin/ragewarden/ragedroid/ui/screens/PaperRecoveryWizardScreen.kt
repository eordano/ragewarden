@Composable
fun PaperRecoveryWizardScreen(
    onBack: () -> Unit,
    onComplete: () -> Unit,
    onToast: (String) -> Unit = {},
    onTestNow: (() -> Unit)? = null,
    recipientStore: RecipientStore? = null,
    accountId: String? = null,
) {
    val c = rageColors
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    val model: PaperRecoveryViewModel = viewModel()
    var step by rememberSaveable { mutableStateOf(PaperRecoveryStep.Generate) }
    val generated = model.generated
    var saving by remember { mutableStateOf(false) }
    var saveError by remember { mutableStateOf<String?>(null) }

    val attemptPersist: () -> Unit = persist@{
        if (saving) return@persist
        val ready = generated
        if (ready == null) {
            saveError = uiString(R.string.recovery_phrase_is_still_being_generated)
            return@persist
        }
        if (recipientStore == null || accountId.isNullOrBlank()) {
            saveError = uiString(R.string.configuration_error_no_active_account_sign)
            return@persist
        }
        saving = true
        scope.launch {
            val result = runCatching { recipientStore.add(accountId, enrollRecovery(ready)) }
            saving = false
            result.onSuccess {
                saveError = null
                step = PaperRecoveryStep.Done
                runCatching {
                    context.appEntryPoint().auditFeed().record(
                        action = AuditAction.EnrollIdentity,
                        item = uiString(R.string.paper_recovery),
                        reason = uiString(R.string.recovery_recipient_added),
                    )
                }
                runCatching { VaultBridge.repository()?.pushRecipientRegistry() }
            }.onFailure { e ->
                saveError = if (e is ragewarden.ragedroid.data.StoreUnreadableException) {
                    context.getString(R.string.key_list_unreadable_enrol)
                } else {
                    uiString(R.string.we_couldn_t_save_your_recovery)
                }
                onToast(uiString(R.string.save_failed, e.message ?: e::class.simpleName.orEmpty()))
            }
        }
    }
    val mnemonic = generated?.mnemonic
    val phrase: ImmutableList<String> = remember(mnemonic) {
        mnemonic?.split(' ', '\t', '\n')
            ?.filter { it.isNotBlank() }
            ?.toImmutableList()
            ?: LOADING_PHRASE
    }
    val challenge = model.challenge(phrase.size)
    val answers = model.answers

    val allCorrect = challenge.all { i ->
        (answers.value[i] ?: "").trim().lowercase() == phrase[i]
    }

    Column(modifier = Modifier.fillMaxSize().background(c.background)) {
        when (step) {
            PaperRecoveryStep.Generate -> {
                AppBar(
                    title = stringResource(R.string.paper_recovery),
                    subtitle = stringResource(R.string.step_1_of_2),
                    leading = { BackButton(onBack) },
                )
                Column(
                    modifier = Modifier
                        .fillMaxSize()
                        .verticalScroll(rememberScrollState())
                        .padding(start = 18.dp, end = 18.dp, bottom = 18.dp),
                ) {
                    Text(
                        text = stringResource(R.string.write_these_24_words_down),
                        style = RageType.h1.copy(
                            fontSize = 22.sp,
                            lineHeight = 26.sp,
                            letterSpacing = (-0.015).em,
                        ),
                        color = c.fgEmphasis,
                    )
                    Spacer(modifier = Modifier.height(10.dp))
                    Text(
                        text = stringResource(R.string.this_phrase_is_your_last_resort),
                        style = RageType.body.copy(
                            fontSize = 14.5.sp,
                            lineHeight = 22.sp,
                        ),
                        color = c.fgPrimary,
                    )
                    Spacer(modifier = Modifier.height(16.dp))
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .background(c.surfaceElevated, RoundedCornerShape(12.dp))
                            .border(1.dp, c.border, RoundedCornerShape(12.dp))
                            .padding(horizontal = 14.dp, vertical = 16.dp),
                    ) {
                        val rows = phrase.size / 2
                        for (rowIndex in 0 until rows) {
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.spacedBy(14.dp),
                            ) {
                                PhraseWord(
                                    index = rowIndex,
                                    word = phrase[rowIndex],
                                    modifier = Modifier.weight(1f),
                                )
                                PhraseWord(
                                    index = rowIndex + rows,
                                    word = phrase[rowIndex + rows],
                                    modifier = Modifier.weight(1f),
                                )
                            }
                            if (rowIndex < rows - 1) {
                                Spacer(modifier = Modifier.height(8.dp))
                            }
                        }
                    }
                    Spacer(modifier = Modifier.height(14.dp))
                    WarningCalloutPaper(
                        text = stringResource(R.string.don_t_screenshot_don_t_type),
                    )
                    Spacer(modifier = Modifier.height(14.dp))
                    RageButton(
                        label = stringResource(R.string.print_recovery_sheet),
                        onClick = {
                            val ready = generated
                            if (ready == null) {
                                onToast(uiString(R.string.recovery_phrase_is_still_being_generated))
                            } else {
                                printRecoverySheet(context, ready)
                            }
                        },
                        icon = Icons.Outlined.Description,
                        variant = ButtonVariant.Secondary,
                        fullWidth = true,
                    )
                    Spacer(modifier = Modifier.height(8.dp))
                    RageButton(
                        label = stringResource(R.string.i_ve_written_them_down),
                        onClick = { step = PaperRecoveryStep.Verify },
                        icon = Icons.AutoMirrored.Outlined.ArrowForward,
                        fullWidth = true,
                    )
                }
            }
            PaperRecoveryStep.Verify -> {
                AppBar(
                    title = stringResource(R.string.confirm),
                    subtitle = stringResource(R.string.step_2_of_2),
                    leading = {
                        IconBtn(
                            icon = Icons.AutoMirrored.Outlined.ArrowBack,
                            contentDescription = stringResource(R.string.back),
                            onClick = { step = PaperRecoveryStep.Generate },
                        )
                    },
                )
                Column(
                    modifier = Modifier
                        .fillMaxSize()
                        .verticalScroll(rememberScrollState())
                        .padding(start = 18.dp, end = 18.dp, bottom = 18.dp),
                ) {
                    Text(
                        text = stringResource(R.string.type_3_words_to_confirm),
                        style = RageType.h1.copy(
                            fontSize = 22.sp,
                            lineHeight = 26.sp,
                            letterSpacing = (-0.015).em,
                        ),
                        color = c.fgEmphasis,
                    )
                    Spacer(modifier = Modifier.height(10.dp))
                    Text(
                        text = stringResource(R.string.we_ll_only_verify_these_three),
                        style = RageType.body.copy(fontSize = 14.5.sp, lineHeight = 22.sp),
                        color = c.fgSecondary,
                    )
                    Spacer(modifier = Modifier.height(16.dp))
                    Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                        challenge.forEach { i ->
                            val ans = answers.value[i] ?: ""
                            val correct = ans.isNotEmpty() && ans.trim().lowercase() == phrase[i]
                            val wrong = ans.isNotEmpty() && !correct
                            Field(label = stringResource(R.string.word, i + 1)) {
                                Box {
                                    Box(
                                        modifier = Modifier
                                            .fillMaxWidth()
                                            .border(
                                                1.dp,
                                                when {
                                                    correct -> c.success
                                                    wrong -> c.danger
                                                    else -> c.border
                                                },
                                                RoundedCornerShape(8.dp),
                                            ),
                                    ) {
                                        TextInput(
                                            value = ans,
                                            onValueChange = { v ->
                                                answers.value = answers.value + (i to v)
                                            },
                                            placeholder = stringResource(R.string.word_2, i + 1),
                                            mono = true,
                                        )
                                    }
                                    if (correct) {
                                        Icon(
                                            imageVector = Icons.Outlined.Check,
                                            contentDescription = null,
                                            tint = c.success,
                                            modifier = Modifier
                                                .align(Alignment.CenterEnd)
                                                .padding(end = 12.dp)
                                                .size(16.dp),
                                        )
                                    }
                                }
                            }
                        }
                    }
                    Spacer(modifier = Modifier.height(8.dp))
                    RageButton(
                        label = when {
                            saving -> stringResource(R.string.saving)
                            allCorrect -> stringResource(R.string.confirm_recipient)
                            else -> stringResource(R.string.all_three_must_match)
                        },
                        onClick = attemptPersist,
                        icon = Icons.Outlined.Check,
                        fullWidth = true,
                        enabled = allCorrect && !saving,
                    )
                }
            }
            PaperRecoveryStep.Done -> {
                AppBar(title = stringResource(R.string.recipient_enrolled))
                PaperRecoveryDone(onTestNow = onTestNow, onComplete = onComplete)
            }
        }
    }

    val errorMessage = saveError
    if (errorMessage != null) {
        val isMisconfig = recipientStore == null || accountId.isNullOrBlank()
        AlertDialog(
            onDismissRequest = {},
            title = { Text(stringResource(R.string.save_failed_2)) },
            text = {
                Column {
                    Text(
                        text = errorMessage,
                        style = RageType.body.copy(fontSize = 14.sp, lineHeight = 20.sp),
                        color = c.fgPrimary,
                    )
                    if (!isMisconfig) {
                        Spacer(modifier = Modifier.height(12.dp))
                        Box(
                            modifier = Modifier
                                .fillMaxWidth()
                                .background(c.surfaceSunken, RoundedCornerShape(8.dp))
                                .border(1.dp, c.border, RoundedCornerShape(8.dp))
                                .padding(horizontal = 12.dp, vertical = 10.dp),
                        ) {
                            Text(
                                text = phrase.joinToString(" "),
                                style = RageType.mono.copy(
                                    fontFamily = FontFamily.Monospace,
                                    fontSize = 13.sp,
                                    lineHeight = 19.sp,
                                ),
                                color = c.fgEmphasis,
                            )
                        }
                    }
                }
            },
            confirmButton = {
                if (isMisconfig) {
                    TextButton(onClick = {
                        saveError = null
                        onBack()
                    }) { Text(stringResource(R.string.back)) }
                } else {
                    TextButton(
                        enabled = !saving,
                        onClick = {
                            saveError = null
                            attemptPersist()
                        },
                    ) { Text(stringResource(R.string.retry)) }
                }
            },
            dismissButton = {
                if (!isMisconfig) {
                    TextButton(onClick = {
                        saveError = null
                        onBack()
                    }) { Text(stringResource(R.string.cancel)) }
                }
            },
        )
    }
}

