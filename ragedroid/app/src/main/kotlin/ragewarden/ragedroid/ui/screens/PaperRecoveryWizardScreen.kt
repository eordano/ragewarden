private enum class PaperRecoveryStep { Generate, Verify, Done }

class PaperRecoveryViewModel : ViewModel() {
    var generated by mutableStateOf<GeneratedRecovery?>(null)
        private set
    val answers = mutableStateOf(emptyMap<Int, String>())
    private var challengeFor: Int = -1
    private var challengeIdx: List<Int> = emptyList()

    init {
        viewModelScope.launch { generated = withContext(Dispatchers.IO) { Recovery.generate() } }
    }

    fun challenge(size: Int): List<Int> {
        if (size != challengeFor) {
            val rng = SecureRandom()
            val set = mutableSetOf<Int>()
            while (set.size < minOf(3, size)) set.add(rng.nextInt(size))
            challengeIdx = set.sorted()
            challengeFor = size
        }
        return challengeIdx
    }
}

